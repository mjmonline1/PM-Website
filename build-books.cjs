for (const p of printables) {
  for (const f of [`images/printables/${p.slug}-page.webp`, `images/printables/${p.slug}-pin.jpg`, `images/printables/${p.packImg}`, `downloads/${p.slug}-free-letter.pdf`, `downloads/${p.slug}-free-a4.pdf`])
    if (!fs.existsSync(path.join(root, f))) throw new Error(`${p.slug}: missing ${f}`);
  if (p.etsy.startsWith('/') && !fs.readFileSync(path.join(root, '_redirects'), 'utf8').includes(p.etsy + ' ')) throw new Error(`${p.slug}: ${p.etsy} not in _redirects`);
  fs.mkdirSync(path.join(root, 'printables', p.slug), { recursive: true });
  fs.writeFileSync(path.join(root, 'printables', p.slug, 'index.html'), printablePage(p));
}

const today = new Date().toISOString().slice(0, 10);
const urls = ['/', '/books/', ...books.map(b => `/books/${b.slug}/`), ...onSite.map(p => `/printables/${p.slug}/`)];
fs.writeFileSync(path.join(root, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map(u => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod></url>`).join('\n') +
  `\n</urlset>\n`);

// Homepage free-printables line, between <!-- PRINTABLES --> markers: live pages only.
{
  const names = onSite.map(printableLink), joined = names.length > 1 ? names.slice(0, -1).join(', ') + ' and ' + names[names.length - 1] : names[0];
  const h = fs.readFileSync(homeFile, 'utf8'), re = /(<!-- PRINTABLES -->)[\s\S]*?(<!-- \/PRINTABLES -->)/;
  if (!re.test(h)) throw new Error('index.html: <!-- PRINTABLES --> markers missing');
  let out = h.replace(re, names.length ? `$1<p class="free-line">Or grab a free word search printable now, no sign-up: ${joined}.</p>$2` : '$1$2');
  // Homepage "Printable puzzle packs" section, between <!-- PACKS --> markers: one card per live pack, Etsy button + free sample.
  const pre = /(<!-- PACKS -->)[\s\S]*?(<!-- \/PACKS -->)/;
  if (!pre.test(out)) throw new Error('index.html: <!-- PACKS --> markers missing');
  const cards = onSite.map(p => `
      <h3 class="collection">${esc(p.pack)}</h3>
      <ul class="printable-list">${p.bullets.map(b => `<li>${esc(b)}</li>`).join('')}</ul>
      <p><a class="btn-primary" href="${esc(p.etsy)}" rel="noopener">Get it on Etsy</a> or <a href="/printables/${p.slug}/">try the free ${esc(p.holiday)} word search</a> first.</p>`).join('\n');
  out = out.replace(pre, onSite.length ? `$1\n    <section class="content-box" id="packs">\n      <h2>Printable puzzle packs</h2>${cards}\n    </section>\n    $2` : '$1$2');
  fs.writeFileSync(homeFile, out);
}

// feed.xml: RSS for Pinterest auto-pin (board Puzzle Books). Live printables not pinned by hand; live date = pubDate.
// Never remove a live item's flag or change its slug: guid = page URL, Pinterest uses it to skip already-pinned items.
const live = onSite.filter(p => !p.pinned).sort((a, b) => b.live.localeCompare(a.live));
fs.writeFileSync(path.join(root, 'feed.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom" xmlns:media="http://search.yahoo.com/mrss/">\n<channel>\n` +
  `  <title>The Puzzle Monsters: Free Printables</title>\n  <link>${SITE}/</link>\n  <description>Free printable word searches with answer keys.</description>\n` +
  `  <atom:link href="${SITE}/feed.xml" rel="self" type="application/rss+xml"/>\n` +
  live.map(p => {
    const url = `${SITE}/printables/${p.slug}/`;
    return `  <item>\n    <title>Free ${esc(p.holiday)} Word Search Printable (PDF + Answer Key)</title>\n    <link>${url}</link>\n    <guid isPermaLink="true">${url}</guid>\n` +
      `    <pubDate>${new Date(p.live + 'T12:00:00Z').toUTCString()}</pubDate>\n    <description>${esc(p.desc)}</description>\n` +
      `    <enclosure url="${SITE}/images/printables/${p.slug}-pin.jpg" length="${fs.statSync(path.join(root, 'images', 'printables', `${p.slug}-pin.jpg`)).size}" type="image/jpeg"/>\n` +
      `    <media:content url="${SITE}/images/printables/${p.slug}-pin.jpg" medium="image" type="image/jpeg" width="1000" height="1500"/>\n  </item>`;
  }).join('\n') + (live.length ? '\n' : '') + `</channel>\n</rss>\n`);

// Self-check: every image a page points at exists, and every book has the fields the template needs.
for (const b of books) {
  for (const k of ['slug', 'asin', 'title', 'subtitle', 'collection', 'blurb', 'metaTitle', 'metaDescription', 'intro', 'faqs', 'coverW', 'coverH'])
    if (b[k] === undefined) throw new Error(`${b.slug}: missing ${k}`);
  if (!b.details && !(b.highlights && b.highlights.length)) throw new Error(`${b.slug}: no details or highlights`);
  for (const f of [`${b.slug}-cover.webp`, b.sample && b.sample.img].filter(Boolean))
    if (!fs.existsSync(path.join(root, 'images', 'books', f))) throw new Error(`missing image images/books/${f}`);
}
// Link check: no generated or homepage link may point at a printable page that isn't live (it would 404 once pushed).
{
  const liveSlugs = new Set(onSite.map(p => p.slug)), bad = [];
  const files = [['index.html'], ['books/index.html'], ...books.map(b => [`books/${b.slug}/index.html`]), ...printables.map(p => [`printables/${p.slug}/index.html`, p.slug])];
  for (const [f, self] of files) for (const m of fs.readFileSync(path.join(root, f), 'utf8').matchAll(/href="(?:https:\/\/www\.thepuzzlemonsters\.com)?\/printables\/([^/"]+)\/?"/g))
    if (!liveSlugs.has(m[1]) && m[1] !== self) bad.push(`${f} -> /printables/${m[1]}/`); // self = a page's own canonical
  if (bad.length) throw new Error('links to printable pages that are not live:\n  ' + bad.join('\n  '));
}
console.log(`built ${books.length} book pages + books/index.html + sitemap (${urls.length} urls) + feed.xml (${live.length} items) + ${onSite.length}/${printables.length} printables live, link check ok`);
