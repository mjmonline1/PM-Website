// Builds one page per book (books/<slug>/index.html) from books.json, then rewrites sitemap.xml.
// Run: node build-books.cjs   (no dependencies). Re-run after any change to books.json.
// Images live in images/books/<slug>-cover.webp and <slug>-sample.webp. They are rendered from
// the book's own cover.pdf / Puzzles.pdf in C:\Books, never hotlinked from Amazon.
// ponytail: books.json is hand-filled for the 3-book pilot. Generate it from Mongo
// Books.Catalogue once the page set grows past a handful of titles.
const fs = require('fs');
const path = require('path');

const SITE = 'https://www.thepuzzlemonsters.com';
const TAG = 'thepuzzlemons-20';
const root = __dirname;
const books = JSON.parse(fs.readFileSync(path.join(root, 'books.json'), 'utf8'));

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// JSON inside <script>: stop "</script>" from closing the tag early.
const ld = o => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');

function page(b) {
  const url = `${SITE}/books/${b.slug}/`;
  const cover = `${SITE}/images/books/${b.slug}-cover.webp`;
  const buy = `https://www.amazon.com/dp/${b.asin}?tag=${TAG}`;
  const skip = b.skipStores ? ` data-skip="${esc(b.skipStores.join(' '))}"` : '';
  const related = books.filter(x => x.slug !== b.slug);

  const jsonld = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Book', '@id': `${url}#book`, name: `${b.title}: ${b.subtitle}`, url,
        image: cover, description: b.metaDescription, inLanguage: 'en', bookFormat: 'https://schema.org/Paperback',
        author: { '@type': 'Person', name: 'The Professor' },
        publisher: { '@id': `${SITE}/#org` },
        sameAs: `https://www.amazon.com/dp/${b.asin}`
      },
      {
        '@type': 'BreadcrumbList', itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Books', item: `${SITE}/#books` },
          { '@type': 'ListItem', position: 2, name: b.collection, item: `${SITE}/#books` },
          { '@type': 'ListItem', position: 3, name: b.title, item: url }
        ]
      }
    ]
  };

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <!-- GENERATED by build-books.cjs from books.json. Edit those, not this file. -->
  <script async src="https://www.googletagmanager.com/gtag/js?id=G-6521TDM9Q9"></script>
  <script>
    window.dataLayer = window.dataLayer || [];
    function gtag(){dataLayer.push(arguments);}
    gtag('js', new Date());
    gtag('config', 'G-6521TDM9Q9');
  </script>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(b.metaTitle)}</title>
  <meta name="description" content="${esc(b.metaDescription)}">
  <link rel="canonical" href="${url}">
  <link rel="stylesheet" href="/style.css">
  <link rel="icon" type="image/x-icon" href="/images/favicon.ico">
  <link rel="apple-touch-icon" sizes="180x180" href="/images/apple-touch-icon.png">
  <meta property="og:type" content="book">
  <meta property="og:site_name" content="The Puzzle Monsters">
  <meta property="og:title" content="${esc(b.metaTitle)}">
  <meta property="og:description" content="${esc(b.metaDescription)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${cover}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(b.metaTitle)}">
  <meta name="twitter:description" content="${esc(b.metaDescription)}">
  <meta name="twitter:image" content="${cover}">
  <script type="application/ld+json">
${ld(jsonld)}
  </script>
</head>
<body>
  <div class="wrapper">
    <nav class="crumbs" aria-label="Breadcrumb"><a href="/">The Puzzle Monsters</a> › <a href="/#books">${esc(b.collection)}</a> › ${esc(b.title)}</nav>

    <section class="content-box book">
      <img class="book-cover" src="/images/books/${b.slug}-cover.webp" width="612" height="792" alt="${esc(b.title)} cover">
      <div class="book-main">
        <h1>${esc(b.title)}</h1>
        <p class="book-sub">${esc(b.subtitle)}</p>
        ${b.intro.map(p => `<p>${esc(p)}</p>`).join('\n        ')}
        <a class="btn-primary" href="${buy}" target="_blank" rel="sponsored noopener"${skip}>Buy on Amazon</a>
      </div>
    </section>

    <section class="content-box">
      <h2>What's inside</h2>
      <dl class="book-details">
        ${b.details.map(([k, v]) => `<dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join('\n        ')}
      </dl>
      <h2>Who it's for</h2>
      <p>${esc(b.suits)}</p>
    </section>

    <section class="content-box">
      <h2>Look inside</h2>
      <figure class="book-sample">
        <img src="/images/books/${b.sample.img}" width="850" height="1100" loading="lazy" alt="${esc(b.sample.alt)}">
        <figcaption>${esc(b.sample.caption)}</figcaption>
      </figure>
    </section>

    <section class="content-box faq">
      <h2>Questions</h2>
      ${b.faqs.map(([q, a]) => `<details><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('\n      ')}
      <a class="btn-primary" href="${buy}" target="_blank" rel="sponsored noopener"${skip}>Buy ${esc(b.title)} on Amazon</a>
    </section>

    <section class="content-box">
      <h2>More from The Puzzle Monsters</h2>
      <ul class="booklist">
        ${related.map(r => `<li><a href="/books/${r.slug}/"><span class="t">${esc(r.title)}</span><span class="d">${esc(r.subtitle)}</span></a></li>`).join('\n        ')}
      </ul>
      <a class="btn-primary" href="/#books">See all our books</a>
    </section>

    <footer class="site-footer">
      <p>&copy; 2026 The Puzzle Monsters &middot; Books available on Amazon</p>
      <p>As an Amazon Associate we earn from qualifying purchases.</p>
    </footer>
  </div>
  <script src="/script.js"></script>
</body>
</html>
`;
}

for (const b of books) {
  const dir = path.join(root, 'books', b.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), page(b));
}

const today = new Date().toISOString().slice(0, 10);
const urls = ['/', ...books.map(b => `/books/${b.slug}/`)];
fs.writeFileSync(path.join(root, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map(u => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod></url>`).join('\n') +
  `\n</urlset>\n`);

// Self-check: every page built, every image it points at exists.
for (const b of books) {
  for (const f of [`${b.slug}-cover.webp`, b.sample.img]) {
    if (!fs.existsSync(path.join(root, 'images', 'books', f))) throw new Error(`missing image images/books/${f}`);
  }
}
console.log(`built ${books.length} book pages + sitemap (${urls.length} urls)`);
