// Builds the book pages from books.json (fill that with: node sync-books.cjs). Run: node build-books.cjs
// No dependencies. Writes:
//   books/<slug>/index.html  one page per book
//   books/index.html         all books, grouped by collection, with covers
//   sitemap.xml              home + /books/ + every book page
//   index.html               ONLY the "Our books" list and the ItemList JSON-LD (rest of the page untouched)
const fs = require('fs');
const path = require('path');

const SITE = 'https://www.thepuzzlemonsters.com';
const TAG = 'thepuzzlemons-20';
const root = __dirname;
const books = JSON.parse(fs.readFileSync(path.join(root, 'books.json'), 'utf8'));
const collections = [...new Set(books.map(b => b.collection))];

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// JSON inside <script>: stop "</script>" from closing the tag early.
const ld = o => JSON.stringify(o, null, 2).replace(/</g, '\\u003c');
// Kindle ASINs only exist in some stores (not .com), so their links start on .co.uk; script.js routes from there.
const buyUrl = b => `https://www.amazon.${b.kindle ? 'co.uk' : 'com'}/dp/${b.asin}?tag=${TAG}`;
const buyAttrs = b => `target="_blank" rel="sponsored noopener"${b.kindle ? ' data-kindle' : ''}${b.skipStores ? ` data-skip="${esc(b.skipStores.join(' '))}"` : ''}`;
const coverImg = (b, cls, lazy) => `<img class="${cls}" src="/images/books/${b.slug}-cover.webp" width="${b.coverW}" height="${b.coverH}"${lazy ? ' loading="lazy"' : ''} alt="${esc(b.title)} cover">`;

const head = ({ title, desc, url, image, type, jsonld }) => `<!DOCTYPE html>
<html lang="en">
<head>
  <!-- GENERATED by build-books.cjs from books.json. Edit those, not this file. -->
  <script async src="https://www.googletagmanager.com/gtag/js?id=G-6521TDM9Q9"></script>
  <script>
    window.dataLayer = window.dataLayer || [];
    function gtag(){dataLayer.push(arguments);}
    gtag('js', new Date());
    gtag('config', 'G-6521TDM9Q9');
  </script>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <link rel="canonical" href="${url}">
  <link rel="stylesheet" href="/style.css">
  <link rel="icon" type="image/x-icon" href="/images/favicon.ico">
  <link rel="apple-touch-icon" sizes="180x180" href="/images/apple-touch-icon.png">
  <meta property="og:type" content="${type}">
  <meta property="og:site_name" content="The Puzzle Monsters">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="${image}">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${esc(title)}">
  <meta name="twitter:description" content="${esc(desc)}">
  <meta name="twitter:image" content="${image}">
  <script type="application/ld+json">
${ld(jsonld)}
  </script>
</head>`;

const foot = `
    <footer class="site-footer">
      <p>&copy; 2026 The Puzzle Monsters &middot; Books available on Amazon</p>
      <p>As an Amazon Associate we earn from qualifying purchases.</p>
    </footer>
  </div>
  <script src="/script.js"></script>
</body>
</html>
`;

function page(b) {
  const url = `${SITE}/books/${b.slug}/`;
  const cover = `${SITE}/images/books/${b.slug}-cover.webp`;
  const related = [...books.filter(x => x.collection === b.collection && x.slug !== b.slug),
                   ...books.filter(x => x.collection !== b.collection)].slice(0, 4);

  const jsonld = {
    '@context': 'https://schema.org',
    '@graph': [
      {
        '@type': 'Book', '@id': `${url}#book`, name: `${b.title}: ${b.subtitle}`, url,
        image: cover, description: b.metaDescription, inLanguage: 'en',
        bookFormat: b.kindle ? 'https://schema.org/EBook' : 'https://schema.org/Paperback',
        author: { '@type': 'Person', name: b.collection === 'Classic Reads' ? 'Charles Dickens' : 'The Professor' },
        publisher: { '@id': `${SITE}/#org` },
        sameAs: `https://www.amazon.${b.kindle ? 'co.uk' : 'com'}/dp/${b.asin}`
      },
      {
        '@type': 'BreadcrumbList', itemListElement: [
          { '@type': 'ListItem', position: 1, name: 'Books', item: `${SITE}/books/` },
          { '@type': 'ListItem', position: 2, name: b.collection, item: `${SITE}/books/#${b.collection.toLowerCase().replace(/\W+/g, '-')}` },
          { '@type': 'ListItem', position: 3, name: b.title, item: url }
        ]
      }
    ]
  };

  const inside = b.details
    ? `<dl class="book-details">
        ${b.details.map(([k, v]) => `<dt>${esc(k)}</dt><dd>${esc(v)}</dd>`).join('\n        ')}
      </dl>`
    : `<ul class="book-highlights">
        ${b.highlights.map(h => `<li>${esc(h)}</li>`).join('\n        ')}
      </ul>
      <p class="book-format">Format: ${esc(b.format)}</p>`;

  return `${head({ title: b.metaTitle, desc: b.metaDescription, url, image: cover, type: 'book', jsonld })}
<body>
  <div class="wrapper">
    <nav class="crumbs" aria-label="Breadcrumb"><a href="/">The Puzzle Monsters</a> › <a href="/books/">Books</a> › ${esc(b.title)}</nav>

    <section class="content-box book">
      ${coverImg(b, 'book-cover')}
      <div class="book-main">
        <h1>${esc(b.title)}</h1>
        <p class="book-sub">${esc(b.subtitle)}</p>
        ${b.intro.map(p => `<p>${esc(p)}</p>`).join('\n        ')}
        <a class="btn-primary" href="${buyUrl(b)}" ${buyAttrs(b)}>Buy on Amazon</a>
      </div>
    </section>

    <section class="content-box book-text">
      <h2>What's inside</h2>
      ${inside}${b.suits ? `
      <h2>Who it's for</h2>
      <p>${esc(b.suits)}</p>` : ''}${b.closing ? `
      <p class="book-closing">${esc(b.closing)}</p>` : ''}
    </section>
${b.sample ? `
    <section class="content-box">
      <h2>Look inside</h2>
      <figure class="book-sample">
        <img src="/images/books/${b.sample.img}" width="850" height="1100" loading="lazy" alt="${esc(b.sample.alt)}">
        <figcaption>${esc(b.sample.caption)}</figcaption>
      </figure>
    </section>
` : ''}
    <section class="content-box faq">
      <h2>Questions</h2>
      ${b.faqs.map(([q, a]) => `<details><summary>${esc(q)}</summary><p>${esc(a)}</p></details>`).join('\n      ')}
      <a class="btn-primary" href="${buyUrl(b)}" ${buyAttrs(b)}>Buy ${esc(b.title)} on Amazon</a>
    </section>

    <section class="content-box">
      <h2>More from The Puzzle Monsters</h2>
      <ul class="booklist">
        ${related.map(r => `<li><a href="/books/${r.slug}/"><span class="t">${esc(r.title)}</span><span class="d">${esc(r.blurb)}</span></a></li>`).join('\n        ')}
      </ul>
      <a class="btn-primary" href="/books/">See all our books</a>
    </section>
${foot}`;
}

function indexPage() {
  const url = `${SITE}/books/`;
  const jsonld = {
    '@context': 'https://schema.org', '@type': 'ItemList', name: 'The Puzzle Monsters — Books',
    itemListElement: books.map((b, i) => ({ '@type': 'ListItem', position: i + 1, url: `${SITE}/books/${b.slug}/` }))
  };
  const sections = collections.map(c => `
    <section class="content-box" id="${c.toLowerCase().replace(/\W+/g, '-')}">
      <h2>${esc(c)}</h2>
      <ul class="covergrid">
        ${books.filter(b => b.collection === c).map(b => `<li><a href="/books/${b.slug}/">${coverImg(b, '', true)}<span class="t">${esc(b.title)}</span><span class="d">${esc(b.blurb)}</span></a></li>`).join('\n        ')}
      </ul>
    </section>`).join('\n');
  return `${head({ title: 'All Puzzle Books: Word Search, Connections & More | The Puzzle Monsters',
    desc: `All ${books.length} books from The Puzzle Monsters: word search, Connections, sudoku, codewords, cryptograms, a Dublin pocket guide and annotated Dickens classics.`,
    url, image: `${SITE}/images/android-chrome-512x512.png`, type: 'website', jsonld })}
<body>
  <div class="wrapper">
    <nav class="crumbs" aria-label="Breadcrumb"><a href="/">The Puzzle Monsters</a> › Books</nav>
    <header class="content-box hero">
      <h1>All our books</h1>
      <h2>Every book, by collection. Tap one to look inside.</h2>
    </header>
${sections}
${foot}`;
}

for (const b of books) {
  const dir = path.join(root, 'books', b.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'index.html'), page(b));
}
fs.writeFileSync(path.join(root, 'books', 'index.html'), indexPage());

// Homepage: regenerate only the book list and the ItemList, so they can't drift from books.json.
const homeFile = path.join(root, 'index.html');
let home = fs.readFileSync(homeFile, 'utf8');
const list = collections.map(c => `
      <h3 class="collection">${esc(c)}</h3>
      <ul class="booklist">
        ${books.filter(b => b.collection === c).map(b => `<li><a href="/books/${b.slug}/"><span class="t">${esc(b.title)}</span><span class="d">${esc(b.blurb)}</span></a></li>`).join('\n        ')}
      </ul>`).join('\n');
const before = home;
home = home.replace(/(<main id="books" class="content-box books">\s*<h2>Our books<\/h2>)[\s\S]*?(\n\s*<\/main>)/,
  `$1\n${list}\n      <p><a class="btn-primary" href="/books/">Browse all books with covers</a></p>$2`);
home = home.replace(/("itemListElement": )\[[\s\S]*?\n    \]/,
  `$1[\n${books.map((b, i) => `      {"@type": "Book", "position": ${i + 1}, "name": ${JSON.stringify(b.title)}, "url": "${SITE}/books/${b.slug}/"}`).join(',\n')}\n    ]`);
if (home === before) console.log('WARN index.html: book list / ItemList markers not found or unchanged');
fs.writeFileSync(homeFile, home);

const today = new Date().toISOString().slice(0, 10);
const PRINTABLES = ['/printables/christmas-word-search/']; // hand-written pages under /printables/
const urls = ['/', '/books/', ...books.map(b => `/books/${b.slug}/`), ...PRINTABLES];
fs.writeFileSync(path.join(root, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map(u => `  <url><loc>${SITE}${u}</loc><lastmod>${today}</lastmod></url>`).join('\n') +
  `\n</urlset>\n`);

// Self-check: every image a page points at exists, and every book has the fields the template needs.
for (const b of books) {
  for (const k of ['slug', 'asin', 'title', 'subtitle', 'collection', 'blurb', 'metaTitle', 'metaDescription', 'intro', 'faqs', 'coverW', 'coverH'])
    if (b[k] === undefined) throw new Error(`${b.slug}: missing ${k}`);
  if (!b.details && !(b.highlights && b.highlights.length)) throw new Error(`${b.slug}: no details or highlights`);
  for (const f of [`${b.slug}-cover.webp`, b.sample && b.sample.img].filter(Boolean))
    if (!fs.existsSync(path.join(root, 'images', 'books', f))) throw new Error(`missing image images/books/${f}`);
}
console.log(`built ${books.length} book pages + books/index.html + sitemap (${urls.length} urls)`);
